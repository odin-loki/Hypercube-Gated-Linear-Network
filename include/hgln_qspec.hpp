// HGLN v5.0 INTEGER SPECIFICATION
// Every quantity below is an integer; the only floating-point operations are the conversions of the caller's
// inputs/targets/parameters (multiplication by a power of two, std::nearbyint in the default round-to-nearest-even
// mode) and of the returned prediction (one IEEE division). Integer sums are exact (or wrap modulo 2^32 where stated),
// so they may be evaluated in any order: scalar, any SIMD width and a GPU give bit-identical results.
//
// 0. Notation. AB = abits, WB = wbits (Params::abits / wbits, each in 12..16; storage is int16 for every width).
//    A value "Qf" is an integer v meaning v / 2^f. The grids follow research/alg/hgln_var.hpp's qn/qsr:
//    frac = bits - 1 - integer bits.
//      activations (inputs, side information s, p*s, z, gates a, heatmap h, unit outputs o):  Q(FA), FA = AB - 2, |.|<2
//      rule outputs f:                                                                       Q(FF), FF = AB - 4, |.|<8
//      rules W:  Q(FW), FW = WB - 4 (|W| < 8);  hyperplanes H:  Q(FH), FH = WB - 2 (|H| < 2);  gate weights p:
//      Q(FP), FP = WB - 3 (0 <= p <= 3).  Saturation: activations to +-MA = +-(2^(AB-1) - 1), state to +-MW.
//      ONE = 2^FA.   Control scalars (errors, gate steps, LMS rate) are int32 in the fixed formats given below;
//      intermediates are int64 (bounds noted).
//    rne(v, k)   = v / 2^k rounded to nearest, ties to even (k <= 0: v * 2^-k):  (v + 2^(k-1) - 1 + ((v >> k) & 1)) >> k
//    sat(v, M)   = min(max(v, -M), M);   >> is an arithmetic (floor) shift.
//    div(n, d)   = n / d rounded to nearest, ties to even (d > 0), exact integer division.
//    isqrt(n)    = floor(sqrt(n)) of a uint64 (exact).
//    sr(Y, F, r) = stochastic rounding of Y / 2^F with a 16-bit random r:  (Y >> F) + (r < frac16), frac16 = the top
//                  16 bits of the F fraction bits of Y (F >= 16 here).  P(round up) = frac16 / 2^16.
//
// 1. Random numbers: Philox4x32-10 (Salmon et al., SC'11 / Random123; the same algorithm as FORGE's
//    support/include/forge/rand/philox.hpp), key = (seed lo32, seed hi32) of the network seed, counter
//    (c0, c1, c2, c3) = (element block, 4*layer + array, t lo32, t hi32); t = number of learn() calls before this one.
//    Each block gives 4 words = 8 16-bit halves (half 0 = low 16 bits).  Element -> (c0, word, half):
//      W  (array 0) unit k, active slot q (q-th active column of unit k, ascending; bias last), corner c:
//                   c0 = k<<16 | (q>>3)<<4 | c,      word (q>>1)&3, half q&1
//      H  (array 1) unit k, bit b, input i:  c0 = ((i>>3)*4 + b)<<4 | k,   word (i>>1)&3, half i&1
//      p  (array 2) unit k, input i:         c0 = (i>>3)<<4 | k,            word (i>>1)&3, half i&1
//      initial hyperplanes (array 3, t = 2^64 - 1): c0 = (i*4 + b)<<4 | k; v = sum of the 8 halves of words 0..3
//                   ... see init_hyperplane() (sum of 4 halves of words 0,1 minus 131070: Irwin-Hall approximation
//                   of a Gaussian), last (bias) component 0, then H_i = sat(div(v_i << FH, isqrt(sum v^2)), MW).
//
// 2. Input.  xq_j = sat(nearbyint(x_j * 2^FA), MA)  (NaN -> 0; the conversion clamps before rounding).
//    Side information (unit vector [x, 1] / |[x, 1]|):  nn = ONE^2 + sum xq_j^2 (int64);  g = isqrt(nn << 6);
//    rcp = floor(2^(34+FA) / g);  s_j = rne(xq_j * rcp, 31) (j < d),  s_d = rne(ONE * rcp, 31).
//    Layer inputs: layer 1 reads xq, layer 2 reads layer 1's outputs o, layer 3 reads layer 2's (Params::fanout:
//    layer 1's). x_n = ONE (bias column).
//
// 3. Gates (all three layers first; they depend only on s and, for the latch, on layer 1's gates):
//    ps_i = sat(rne(p_i * s_i, FP), MA);  z_b = sum_i H_bi * ps_i (int32);  zq_b = sat(rne(z_b, FH), MA).
//    Sigmoid table kSigLut (1025 int16 entries, Q14): L[i] = round_even(16384 clip(sigmoid(12 (i - 512)/512), 1e-4,
//    1-1e-4)), generated by scripts/gen_qlut.py in exact decimal arithmetic.  sig14(v), v in Q14:
//    vc = clamp(v, -16384, 16383), i = (vc + 16384) >> 5, r = (vc + 16384) & 31, sig14 = L[i] + ((L[i+1]-L[i]) r + 16) >> 5
//    (linear interpolation; within 1.02 Q14 LSB of the exact clipped sigmoid).  z14 = zq << (16 - AB).
//    plain gate:   a14 = sig14(z14).
//    cross-layer latch (Params::latch = theta > 0, layers 2 and 3; both latch on layer 1's bits with fan-out, else on
//    the layer they read): th14 = round_even(theta * 2^FA) << (16-AB), st = sig14(z14 - th14), rt = sig14(-z14 - th14),
//    q14 = a_lower << (16-AB),  a14 = clamp(st + rne((16384 - st - rt) q14, 14), 2, 16382),
//    kap14 = rne(rne(st (16384 - st), 14) (16384 - q14), 14) + rne(rne(rt (16384 - rt), 14) q14, 14).
//    a_b = clamp(rne(a14, 16 - AB), 1, ONE - 1).
//
// 4. Heatmap (tensor product, bit 0 first, rounded after each product):  x_b = bit_b(c) ? a_b : ONE - a_b;
//    hs_c = rne(rne(rne(x_0 x_1, FA) x_2, FA) x_3, FA).
//    Top-k corners (Params::corners = k, 1..16): key_c = 16 hs_c + (15 - c) (ties -> lower corner index first);
//    selected iff #{c' : key_c' > key_c} < k.  k = 16: h = hs.  Otherwise sm = max(1, sum_selected hs);
//    R = floor(2^30 / sm) (uint32, one division per unit);  h_c = selected ? rne(hs_c R, 30 - FA) : 0.
//
// 5. Rules, mixture, output.  f_c = sat(rne(sum_{active j} W_cj x_j, WB - 2), MA)   (the sum is int32 with two's-
//    complement wrap-around, i.e. modulo 2^32; it cannot overflow unless sum |W x| >= 32);
//    mix = sum_c h_c f_c (int32);  o_k = sat(rne(mix, FF), MA).
//    Plain average over the NU = 3U units: S = sum o (int32); the prediction is the double S / (NU * 2^FA).
//
// 6. Learning (y = target).  yq = clamp(nearbyint(y 2^FA), +-2^(FA+6));  eg = div(NU yq - S, NU);
//    es_i = rne((65536 - G) (yq - o_i) + G eg, 16),  G = round_even(glob 65536)                    [Q(FA), int32]
//    gate rate gl(t) = glr1 + (glr0 - glr1) exp(-t / tau) as Q24 int32, computed by gl_q24() below: X = round(t 2^32
//    / tau) (two IEEE operations), exp(-X / 2^32) in Q30 integer arithmetic (table e^-n, 14-term Taylor series).
//    ge_k = sat32(rne(gl e_k, FA)), e_k = the gate error (see gate_err below)                                [Q24]
//    Per layer and unit (F1_b, tot over the SELECTED corners only, with the soft heatmap hs - straight-through):
//      hf_c = hs_c f_c;  tot = sum hf;  F1_b = sum_{bit b set} hf;  num_b = F1_b (ONE - a_b) - (tot - F1_b) a_b  [int64]
//      plain:  Gt_b = sat32(rne(12 num_b, 3 AB - 32))                                          [Q24 = d mix / d z_b]
//      latch:  Gt_b = dz(kap14) with dz(k) = sat32(div(12 k num_b, a_b (ONE - a_b) 2^(FF-10)))  [Q24; = 12 kap (F1/a -
//              F0/(1-a)); for FF < 10 the numerator is multiplied by 2^(10-FF) instead]
//      cb_b = clamp(rne(ge Gt_b, 18), +-53687091) + routed_b                               [Q30; 0.05 = 53687091]
//      latch credit (Params::latch_credit = scale > 0; latched layers only): Gc = sat32(rne(sat32(rne(dz(kap14 of the
//      lower layer's bit) hold14, 14)) CS, 16)), CS = round_even(scale 65536); the lower layer's routed_b (same unit
//      and bit) += clamp(rne(ge Gc, 18), +-53687091). Layers are updated 3, 2, 1, so layer 1 gets it in the same step.
//      ge for the gates: Params::gate_err = 0 the mixed error es, 1 the unit's own error yq - o, 2 the global eg.
//    p step (old H) and hyperplane step (old p), all inputs i < D = d + 1:
//      Y = p_i << (29 + AB) + s_i sum_b cb_b H_bi;   p_i' = clamp(sr(Y, 29 + AB), 0, 3 << FP)
//      Hr_bi = (H_bi << 8) + rne(cb_b (p_i s_i), 19 + AB)                                   [Q(FH + 8), int32]
//      N2_b = sum_i Hr_bi^2 (int64); N2 = 0: H_b unchanged; else rc = floor(2^54 / isqrt(N2_b));
//      H_bi' = sat(sr(Hr_bi rc, 56 - WB), MW)                    (renormalised to unit length on every update)
//    rule step (normalised LMS):  h2 = sum_c h_c^2;  x2 = sum_{active j} x_j^2                              [int64]
//      den = rne(h2, 2 FA - 18) rne(x2, 2 FA - 12) + 1073742                                     [Q30; 1e-3 at Q30]
//      c2 = sat32(div((M es_k) << (38 - FA), den)), M = round_even(mu 65536)                                 [Q24]
//      sc_c = sat32(rne(c2 h_c, FA))                                                                         [Q24]
//      W_cj' = sat(sr((W_cj << F) + sc_c x_j, F), MW),  F = 26 + AB - WB, for every active column j
//      (unselected corners have sc = 0: W is unchanged, no random number is consumed).
//    activity (until the prune; Q(FA+8), initial div(2^(FA+8), 1000)):  A_j += rne(1311 ((|x_j| << 8) - A_j), 16)
//    t += 1.  Prune (once, the first t >= warm with t % 64 == 0): per unit, nt = n <= 4 ? n : (6 n + 5) / 10 inputs
//    kept; score_j = (sum_c |W_cj|) A_j (int64); stable ascending sort of the active inputs (bias excluded); drop the
//    lowest.  After the prune the activity A is no longer used.
// =====================================================================================================================
